"use strict";

const $ToolHelper = Java.loadClass('com.gregtechceu.gtceu.api.item.tool.ToolHelper');

function processShears(event, material) {
    const shearsItem = $ToolHelper.get(GTToolType.SHEARS, material);
    if (shearsItem.isEmpty()) return;

    const tfcProperty = material.getProperty(InfinityPropertyKey.TFC_PROPERTY);

    if (tfcProperty !== null) {
        const knifeBladeItem = ChemicalHelper.get(InfinityTagPrefix.toolHeadKnife, material, 1);

        if (!knifeBladeItem.isEmpty()) {
            TFCWeldingRecipe(event, shearsItem, knifeBladeItem, knifeBladeItem, material, 'copy_worst', tfcProperty.getAnvilTier(), 1, 1, 'shears'); // Do nonTFCTier and Circuit adjustment
        }
    }
}

function processGTTool(event, toolType, toolHeadTagPrefix, material) {
    const toolItem = $ToolHelper.get(toolType, material);
    const toolHeadItem = ChemicalHelper.get(toolHeadTagPrefix, material, 1);

    if (toolItem.isEmpty() || toolHeadItem.isEmpty()) return;

    const materialName = material.getName();

    // These recipes replace the existing tool recipes generated by GT
    if (toolType === GTToolType.WRENCH) {
        event.recipes.tfc.shaped(
            TFC.isp.of(toolItem).copyForgingBonus().copyHeat(), [
                'BAs',
                'RB '
            ], {
                A: toolHeadItem,
                B: `#c:bolts/${materialName}`,
                R: `#c:rods/${materialName}`,
                s: `#gtceu:crafting_tools/screwdriver`
            }
        ).inputRow(0).inputColumn(1).id(`gtceu:shaped/${toolType.name}_${materialName}`);
    } else if (toolType === GTToolType.WIRE_CUTTER) {
        event.recipes.tfc.shaped(
            TFC.isp.of(toolItem).copyForgingBonus().copyHeat(), [
                ' As',
                'RCR'
            ], {
                A: toolHeadItem,
                C: `#c:small_springs`,
                R: `#c:rods/${materialName}`,
                s: `#gtceu:crafting_tools/screwdriver`
            }
        ).inputRow(0).inputColumn(1).id(`gtceu:shaped/${toolType.name}_${materialName}`);
    } else {
        event.recipes.tfc.shaped(
            TFC.isp.of(toolItem).copyForgingBonus().copyHeat(), [
                'X',
                'R'
            ], {
                X: toolHeadItem,
                R: '#c:rods'
            }
        ).inputRow(0).inputColumn(0).id(`gtceu:shaped/${toolType.name}_${materialName}`);
    }

    const tfcProperty = material.getProperty(InfinityPropertyKey.TFC_PROPERTY);

    if (tfcProperty !== null) {
        TFCMeltingRecipe(event, toolItem, material, getMaterialAmount(toolHeadTagPrefix, material) * 144, toolType.name);
    }
}
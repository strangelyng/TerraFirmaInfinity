StartupEvents.registry('gtceu:material', event => {
    event.create('tfinfinity:sodium_aluminate')
        .liquid(new GTFluidBuilder().temperature(370))
        .components('1x sodium', '1x aluminium', '2x oxygen')
        .flags(GTMaterialFlags.DISABLE_DECOMPOSITION)
        .color(0xE0F2FE)
        .secondaryColor(0x0284C7)
    
    event.create('tfinfinity:aluminium_hydroxide')
        .dust()
        .components('1x aluminium', '3x oxygen', '3x hydrogen')
        .formula('Al(OH)3')
        .flags(GTMaterialFlags.DISABLE_DECOMPOSITION)
        .color(0xEAD8C3)
        .secondaryColor(0xC27D38)
    
    event.create('tfinfinity:alumina')
        .dust()
        .components('2x aluminium', '3x oxygen')
        .flags(GTMaterialFlags.DISABLE_DECOMPOSITION)
        .color(0xEBF1F5)
        .secondaryColor(0xC5D1DA)
    
    event.create('tfinfinity:aluminium_fluoride')
        .dust()
        .liquid(new GTFluidBuilder().temperature(1560))
        .components('1x aluminium', '3x fluorine')
        .flags(GTMaterialFlags.DISABLE_DECOMPOSITION)
        .color(0xE0FDF4)
        .secondaryColor(0x0D9488)
    
    event.create('tfinfinity:aluminium_chloride')
        .dust()
        .components('1x aluminium', '3x chlorine')
        .flags(GTMaterialFlags.DISABLE_DECOMPOSITION)
        .color(0xF4F7E6)
        .secondaryColor(0xD6DBBE)
})